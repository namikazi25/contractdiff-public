#!/usr/bin/env python3
"""Export canonical JSON as offline ``window.DATA`` JavaScript."""
from __future__ import annotations

import argparse
import json
import logging
import os
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
PROTOTYPE_DATA_DIR = ROOT / "prototype" / "data"
EVALUATION_RESULTS = ROOT / "evaluation" / "results.json"


class ExportError(ValueError):
    """Raised when canonical data cannot be safely exported."""


@dataclass(frozen=True)
class ExportSpec:
    source_name: str
    output_name: str
    data_key: str


DATA_EXPORTS = (
    ExportSpec("contracts.json", "contracts.js", "contracts"),
    ExportSpec("templates.json", "templates.js", "templates"),
    ExportSpec("playbook.json", "playbook.js", "playbook"),
    ExportSpec("expected_labels.json", "expected_labels.js", "expectedLabels"),
    ExportSpec("model_outputs.json", "model_outputs.js", "modelOutputs"),
    ExportSpec("baseline_outputs.json", "baseline_outputs.js", "baselineOutputs"),
    ExportSpec("routing.json", "routing.js", "routing"),
)
EVALUATION_EXPORT = ExportSpec("results.json", "evaluation.js", "evaluation")


def load_json(path: Path) -> Any:
    try:
        with path.open(encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError as exc:
        raise ExportError(f"required canonical JSON is missing: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ExportError(
            f"invalid JSON in {path} at line {exc.lineno}, column {exc.colno}: "
            f"{exc.msg}"
        ) from exc


def _javascript_json(value: Any) -> str:
    """Serialise JSON while escaping characters unsafe in script contexts."""

    return (
        json.dumps(value, ensure_ascii=False, indent=2)
        .replace("<", "\\u003c")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def render_assignment(value: Any, *, data_key: str, source_label: str) -> str:
    return (
        f"// Generated from {source_label} by pipeline/export_browser_data.py.\n"
        "// Canonical JSON is the source of truth. Do not edit this file.\n"
        "window.DATA = window.DATA || {};\n"
        f"window.DATA.{data_key} = {_javascript_json(value)};\n"
    )


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        delete=False,
    ) as handle:
        handle.write(content)
        temporary_path = Path(handle.name)
    os.replace(temporary_path, path)


def export_one(
    source_path: Path,
    output_path: Path,
    *,
    data_key: str,
    source_label: str,
) -> Path:
    value = load_json(source_path)
    _atomic_write(
        output_path,
        render_assignment(value, data_key=data_key, source_label=source_label),
    )
    return output_path


def export_all(
    *,
    data_dir: Path = DATA_DIR,
    output_dir: Path = PROTOTYPE_DATA_DIR,
    evaluation_results: Path = EVALUATION_RESULTS,
) -> tuple[list[Path], bool]:
    """Export required data and evaluation when evaluation JSON exists."""

    # Load every required input before writing anything, preventing a partial
    # refresh when one canonical file is absent or malformed.
    loaded = [
        (spec, load_json(data_dir / spec.source_name))
        for spec in DATA_EXPORTS
    ]
    evaluation_value = None
    evaluation_present = evaluation_results.is_file()
    if evaluation_present:
        evaluation_value = load_json(evaluation_results)
    elif (output_dir / EVALUATION_EXPORT.output_name).exists():
        raise ExportError(
            "evaluation/results.json is missing but a stale evaluation.js exists"
        )

    written = []
    for spec, value in loaded:
        output_path = output_dir / spec.output_name
        _atomic_write(
            output_path,
            render_assignment(
                value,
                data_key=spec.data_key,
                source_label=f"data/{spec.source_name}",
            ),
        )
        written.append(output_path)
    if evaluation_present:
        output_path = output_dir / EVALUATION_EXPORT.output_name
        _atomic_write(
            output_path,
            render_assignment(
                evaluation_value,
                data_key=EVALUATION_EXPORT.data_key,
                source_label="evaluation/results.json",
            ),
        )
        written.append(output_path)
    return written, evaluation_present


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    parser.add_argument("--output-dir", type=Path, default=PROTOTYPE_DATA_DIR)
    parser.add_argument(
        "--evaluation-results",
        type=Path,
        default=EVALUATION_RESULTS,
    )
    args = parser.parse_args(argv)
    try:
        written, evaluation_present = export_all(
            data_dir=args.data_dir,
            output_dir=args.output_dir,
            evaluation_results=args.evaluation_results,
        )
    except (OSError, ExportError) as exc:
        logger.error("Browser data export failed: %s", exc)
        return 1
    logger.info("Wrote %d browser data files to %s", len(written), args.output_dir)
    if not evaluation_present:
        logger.info(
            "Skipped evaluation.js: evaluation/results.json will be produced "
            "by evaluation/evaluate.py."
        )
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    raise SystemExit(main())
